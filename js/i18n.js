export const LANGS = ['vi', 'en'];
const KEY = 'bhud.lang';
let lang = (() => {
  try { const l = localStorage.getItem(KEY); if (DICT[l]) return l; } catch { /* storage unavailable */ }
  const navLang = globalThis.navigator?.language || '';
  if (navLang.startsWith('en')) return 'en';
  return 'vi'; // Default to Vietnamese
})();
const listeners = new Set();

export const getLang = () => lang;
export function t(key, vars = {}) {
  const s = DICT[lang]?.[key] ?? DICT.vi[key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}
export function onLangChange(fn) { listeners.add(fn); }
export function setLang(l) {
  if (!DICT[l]) return;
  lang = l;
  try { localStorage.setItem(KEY, l); } catch { /* storage unavailable */ }
  applyI18n();
  listeners.forEach(fn => fn(l));
}
export function applyI18n(root = document) {
  root.documentElement && (root.documentElement.lang = lang);
  root.querySelectorAll('[data-i18n]').forEach(el => { el.innerHTML = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
